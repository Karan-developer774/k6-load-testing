import { TestConfiguration } from '@k6-platform/shared-types';
import { buildK6Scenarios } from './options-builder.js';
import { buildK6Thresholds } from './threshold-builder.js';
import { buildK6Request } from './request-builder.js';

export interface GeneratedK6Artifact {
  scriptContent: string;
  envVars: Record<string, string>;
}

export function generateK6Script(config: TestConfiguration): GeneratedK6Artifact {
  const scenarios = buildK6Scenarios(config.loadProfile);
  const thresholds = buildK6Thresholds(config.thresholds);
  const requestArtifact = buildK6Request(config.request);

  const k6Options = {
    scenarios,
    thresholds,
    insecureSkipTLSVerify: config.request.insecureSkipTlsVerify ?? false,
  };

  const scriptContent = `// Automatically generated by Antigravity k6 Load Testing Platform
// Generated at: ${new Date().toISOString()}
// Test Name: ${config.name}

import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = ${JSON.stringify(k6Options, null, 2)};

export default function () {
${requestArtifact.code}
}

export function handleSummary(data) {
  return {
    'summary.json': JSON.stringify(data),
    stdout: textSummary(data, { indent: ' ', enableColors: false }),
  };
}

function textSummary(data, options) {
  return 'Execution finished with ' + (data.metrics.http_reqs ? data.metrics.http_reqs.values.count : 0) + ' requests.';
}
`;

  return {
    scriptContent,
    envVars: requestArtifact.envVars,
  };
}
